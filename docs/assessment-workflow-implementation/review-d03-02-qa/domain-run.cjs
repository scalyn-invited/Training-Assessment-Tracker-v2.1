const fs = require('node:fs');
const path = require('node:path');
const {spawnSync} = require('node:child_process');
const out=__dirname, root=process.cwd();
const env={};
for(const k of ['PATH','Path','SYSTEMROOT','SystemRoot','COMSPEC','ComSpec','USERPROFILE','LOCALAPPDATA','PATHEXT']) if(process.env[k]) env[k]=process.env[k];
for(const dir of ['.','apps/web']) if(fs.readdirSync(dir).some(n=>/^\.env(?:\.(?:local|development|production|test)(?:\.local)?)?$/.test(n))) throw Error('Unexpected environment file');
const tag=process.argv[2];
if(!/^[a-z0-9-]+$/.test(tag||'')) throw Error('Provide unique evidence tag');
const temp=path.resolve('docs/assessment-workflow-implementation/review-d03-02-qa/runtime-'+tag);
if(fs.existsSync(temp)) throw Error('Use a fresh tag/storage');
fs.mkdirSync(temp,{recursive:true});
Object.assign(env,{TEMP:temp,TMP:temp,TMPDIR:temp,AI_LIVE_ENABLED:'false',SMTP_ENABLED:'false',ACCOUNT_EMAIL_ENABLED:'false',DOTENV_CONFIG_PATH:path.join(temp,'no-env'),NODE_OPTIONS:'--trace-warnings'});
const check=spawnSync(process.execPath,['docs/assessment-workflow-implementation/qa-port-check.cjs'],{env,encoding:'utf8'});
fs.writeFileSync(path.join(out,tag+'-isolation.log'),check.stdout+check.stderr);
if(check.status!==0) process.exit(check.status||1);
const files=process.argv.slice(3);
if(!files.length || files.some(f=>!/^tests\/[a-z0-9-]+\.test\.ts$/.test(f) || !fs.existsSync(f))) throw Error('Explicit existing bounded test files required');
const args=['node_modules/vitest/vitest.mjs','run','--hookTimeout=180000','--reporter=verbose','--reporter=json','--outputFile='+path.join(out,tag+'.json'),...files];
if(tag.startsWith('diagnostic-')) args.push('--config',path.join(out,'diagnostic.config.ts'));
console.log(JSON.stringify({command:[process.execPath,...args],temp,liveAdapters:false}));
const log=fs.openSync(path.join(out,tag+'.log'),'wx');
const result=spawnSync(process.execPath,args,{cwd:root,env,stdio:['ignore',log,log],timeout:600000});
fs.closeSync(log);
fs.appendFileSync(path.join(out,tag+'.log'),'\nEXIT '+result.status+'\n'+(result.error?.message||''));
console.log('EXIT',result.status); process.exitCode=result.status??1;
